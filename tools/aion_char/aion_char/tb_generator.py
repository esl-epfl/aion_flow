def header(script: str, netlist: str, lib: str) -> str:
    return (
        f"{SPDX}\n"
        f"// AUTO-GENERATED by {script} from {netlist} -- do not edit.\n"
        f"// Gold model derived from the Liberty functions in {lib}\n"
    )


def emit_tb(gm: GoldModel, script: str, netlist: str, lib: str) -> str:
    mod = gm.module
    ni = len(mod.inputs)
    no = len(mod.outputs)
    tb = f"tb_{mod.name}"
    w = max(len(gm.gold_name(a.net)) for a in gm.assigns)

    lines: list[str] = []
    add = lines.append
    add(header(script, netlist, lib))
    add("`timescale 1ns/1ps")
    add("`default_nettype none")
    add("")
    add(f"module {tb};")
    add("")
    add(f"  localparam int NI = {ni};")
