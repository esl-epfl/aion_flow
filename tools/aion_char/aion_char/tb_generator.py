REF_PREFIX = "reference_"
PWR = ["VDD", "VSS"]


def spice_ports(mod: Module) -> list[str]:
    """The port order a SPICE view of `mod` must use: Verilog header order, then VDD VSS."""
    return mod.inputs + mod.outputs + PWR


def spice_header(script: str, netlist: str, lib: str) -> str:
    return (
        f"* SPDX-License-Identifier: Apache-2.0 WITH SHL-2.1\n"
        f"* AUTO-GENERATED by {script} from {netlist} -- do not edit.\n"
        f"* Gold model derived from the Liberty functions in {lib}\n"
    )


def emit_reference_lib(
    models: list[GoldModel], cell_ports: dict[str, tuple[list[str], Path]],
    script: str, netlist: str, lib: str,
) -> str:
    """`aion_cells.v` re-expressed as SPICE subckts, one per module.

    Named `reference_<module>` so the plain module name stays free for the user's own
    implementation, and so a failure message can say unambiguously which one disagreed.
    """
    lines = [spice_header(script, netlist, lib), "* Transistor-level view of every module in " + netlist + "."]
    for gm in models:
        mod = gm.module
        lines.append("")
        lines.append(f"* {mod.name}: {len(mod.instances)} standard cells")
        lines.append(f".subckt {REF_PREFIX}{mod.name} " + " ".join(spice_ports(mod)))
        for inst in mod.instances:
            ports, _ = cell_ports[inst.cell]
            pins = []
            for p in ports:
                if p in PWR:
                    pins.append(p)
                elif p in inst.conns:
                    pins.append(inst.conns[p])
                else:
                    raise GenError(
                        f"module '{mod.name}': instance '{inst.name}' does not connect pin "
                        f"'{p}' of '{inst.cell}', which the SPICE subckt requires"
                    )
            lines.append(f"X{inst.name} " + " ".join(pins) + f" {inst.cell}")
        lines.append(".ends")
    return "\n".join(lines) + "\n"


def _pwl(sig: str, bit: int, nvec: int, period: str, edge: str) -> str:
    """PWL for one input: bit `bit` of the vector index, one vector per period."""
    lvl = {0: "0", 1: "'VDD'"}  # unquoted '1*VDD' would be parsed as a parameter
    pts = ["0 0"]
    prev = 0
    for v in range(nvec):
        cur = (v >> bit) & 1
        if cur != prev:
            pts.append(f"'{v}*{period}-{edge}' {lvl[prev]}")
            pts.append(f"'{v}*{period}' {lvl[cur]}")
            prev = cur
    return f"V{sig} {sig} 0 PWL(" + " ".join(pts) + ")"


def emit_spice_tb(
    gm: GoldModel,
    custom: str | None,
    ctx: dict[str, str],
    script: str,
    netlist: str,
    lib: str,
) -> str:
    mod = gm.module
    nvec = 2 ** len(mod.inputs)
    period, edge, tstep, vdd = ctx["period"], ctx["edge"], ctx["tstep"], ctx["vdd"]

    duts = [("ref", f"{REF_PREFIX}{mod.name}", "reference")]
    if custom:
        duts.append(("cus", custom, "custom"))

    L: list[str] = []
    add = L.append
    add(spice_header(script, netlist, lib))
    add(f"* {mod.name}: {nvec} exhaustive vectors, one per {period}, checked at the strobe.")
    add(
        "* Agreeing implementations: gold (Liberty B-sources), reference (transistors from "
        + netlist
        + ")"
        + (", custom (user netlist)" if custom else "  [no custom netlist supplied]")
    )
    add("")
    add(ctx["models"])
    for inc in ctx["includes"].splitlines():
        add(inc)
    add("")
    if ctx.get("temp"):
        add(f".temp {ctx['temp']}")
    add(f".param VDD={vdd}")
    add(".param VTH='VDD/2'")
    add("")
    add("* ---- stimulus ----")
    add("Vvdd VDD 0 {VDD}")
    add("Vvss VSS 0 0")
    for b, sig in enumerate(mod.inputs):
        add(_pwl(sig, b, nvec, period, edge))
    add(
        f"Vclk clk 0 PULSE(0 1 '{period}-{ctx['strobe']}-{edge}' 1p 1p "
        f"'{ctx['strobe']}' '{period}')"
    )
    add("")
    for tag, subckt, what in duts:
        add(f"* ---- {what} ----")
        nodes = mod.inputs + [f"{o}_{tag}" for o in mod.outputs] + ["VDD", "VSS"]
        add(f"X{tag} " + " ".join(nodes) + f" {subckt}")
    add("")
    add("* ---- gold: one B-source per standard cell, function taken from Liberty ----")
    for ga in gm.assigns:
        name = gm.gold_name(ga.net)
        add(
            f"Bg_{ga.net} {name} 0 V = {gold_bspice_expr(gm, ga)} ? 1 : 0"
            f"  $ {ga.inst.name} {ga.inst.cell}: {ga.out_pin} = {ga.lib_func}"
        )
    add("")
    add("* ---- pairwise comparison, gated by the strobe ----")

    def lvl(tag: str, o: str) -> str:
        return f"((v(g_{o})>0.5)?1:0)" if tag == "gold" else f"((v({o}_{tag})>VTH)?1:0)"

    pairs = [("gold", tag, f"{what} vs gold") for tag, _, what in duts]
    if custom:
        pairs.append(("ref", "cus", "custom vs reference"))
    for a, b, _ in pairs:
        terms = "+".join(f"abs({lvl(a, o)}-{lvl(b, o)})" for o in mod.outputs)
        add(f"Be_{a}_{b} e_{a}_{b} 0 V = {terms}")
        add(f"Bc_{a}_{b} c_{a}_{b} 0 V = (v(clk)>0.5) ? v(e_{a}_{b}) : 0")
    add("")
    saved = (
        [f"v(c_{a}_{b})" for a, b, _ in pairs]
        + [f"v(g_{o})" for o in mod.outputs]
        + [f"v({o}_{tag})" for tag, _, _ in duts for o in mod.outputs]
        + [f"v({i})" for i in mod.inputs]
        + ["v(clk)"]
    )
    add(".save " + " ".join(saved))
    add(f".tran {tstep} '{nvec}*{period}'")
    add("")
    add(".control")
    add("* ASCII so a rawfile written with -r can be converted to VCD; costs nothing")
    add("* when no -r is given, since then no rawfile is written at all.")
    add("set filetype=ascii")
    add("run")
    add("let fail = 0")
    for a, b, label in pairs:
        add(f"meas tran m_{a}_{b} MAX v(c_{a}_{b})")
        add(f"if m_{a}_{b} > 0.5")
        add(f"  meas tran t_{a}_{b} WHEN v(c_{a}_{b})=0.5 RISE=1")
        add(f"  let v_{a}_{b} = floor(t_{a}_{b} / {period})")
        add(
            f'  echo "[FAIL] {mod.name} : {label} -- first mismatch at vector '
            f'$&v_{a}_{b} (t=$&t_{a}_{b} s)"'
        )
        add("  let fail = 1")
        add("end")
    add("if fail > 0")
    add(f'  echo "[FAIL] {mod.name} : {nvec} vectors checked, mismatches found"')
    add("  quit 1")
    add("else")
    names = ", ".join(["gold"] + [w for _, _, w in duts])
    add(
        f'  echo "[PASS] {mod.name} : {nvec}/{nvec} vectors match '
        f'({1 + len(duts)}-way: {names})"'
    )
    add("end")
    add(".endc")
    add(".end")
    return "\n".join(L) + "\n"


def emit_spice_plot(gm: GoldModel, custom: str | None, script: str, netlist: str) -> str:
    """A ready-made script for ngspice's native plotter, grouped into readable panels.

    ngspice eats the first line of a file as the circuit title, hence the leading comment.
    """
    mod = gm.module
    tb = f"tb_{mod.name}"
    tags = ["ref"] + (["cus"] if custom else [])
    pairs = [f"c_gold_{t}" for t in tags] + (["c_ref_cus"] if custom else [])

    L = [
        f"* Plot script for {tb} -- AUTO-GENERATED by {script} from {netlist}, do not edit.",
        "* ngspice's native plotter, straight off the rawfile: no VCD conversion.",
        f"*   make plot TB={tb}      (or: DISPLAY=:1 ngspice -i {tb}.plot.spice)",
        "* Type 'quit' at the ngspice prompt to close.",
        ".control",
        f"load build/{tb}.raw",
        "* stimulus: the vector index in binary, and the strobe",
        "plot " + " ".join(f"v({i})" for i in mod.inputs) + " v(clk)",
    ]
    for o in mod.outputs:
        traces = [f"v(g_{o})"] + [f"v({o}_{t})" for t in tags]
        L.append(f"* output {o}: gold vs " + ", ".join("reference" if t == "ref" else "custom" for t in tags))
        L.append("plot " + " ".join(traces))
    L.append("* mismatch flags -- flat 0 on a passing run")
    L.append("plot " + " ".join(f"v({p})" for p in pairs))
    L += [".endc", ".end"]
    return "\n".join(L) + "\n"


def emit_report(
    models: list[GoldModel], tables: dict[str, dict[str, list[int]]], script: str, netlist: str, lib: str
) -> str:
    lines = [
        f"<!-- AUTO-GENERATED by {script} from {netlist} -- do not edit. -->",
        "",
        f"# Gold functions for `{netlist}`",
        "",
        f"Oracle: Liberty `function` attributes from `{lib}`.",
        "",
        "For each module: the per-cell gold equations exactly as emitted into the testbench,",
        "and the same outputs flattened down to the primary inputs for review.",
        "",
    ]
    for gm in models:
        mod = gm.module
        lines.append(f"## `{mod.name}`")
        lines.append("")
        lines.append(
            f"{len(mod.inputs)} inputs (`{', '.join(mod.inputs)}`), "
            f"{len(mod.outputs)} outputs (`{', '.join(mod.outputs)}`), "
            f"{2 ** len(mod.inputs)} exhaustive vectors."
        )
        lines.append("")
        lines.append("| instance | cell | Liberty function | gold equation |")
        lines.append("| --- | --- | --- | --- |")
        for ga in gm.assigns:
            lines.append(
                f"| `{ga.inst.name}` | `{ga.inst.cell}` | `{ga.out_pin} = {ga.lib_func}` | "
                f"`{gm.gold_name(ga.net)} = {gold_sv_expr(gm, ga)}` |"
            )
        lines.append("")
        cache: dict[str, str] = {}
        lines.append("Flattened:")
        lines.append("")
        lines.append("```")
        for o in mod.outputs:
            lines.append(f"{o} = {gold_flat_expr(gm, o, cache)}")
        lines.append("```")
        lines.append("")
        lines.append("Truth table (LSB of the index is the first input):")
        lines.append("")
        lines.append("```")
        for o in mod.outputs:
            bits = "".join(str(b) for b in tables[mod.name][o])
            chunks = [bits[i : i + 64] for i in range(0, len(bits), 64)]
            lines.append(f"{o}: {chunks[0]}")
            pad = " " * (len(o) + 2)
            lines.extend(f"{pad}{c}" for c in chunks[1:])
        lines.append("```")
        lines.append("")
    return "\n".join(lines)


