_RE_SUBCKT = re.compile(r"^\s*\.subckt\s+(\S+)\s*(.*)$", re.I)


def parse_spice_subckts(paths: list[Path]) -> dict[str, tuple[list[str], Path]]:
    """Collect ``.subckt <name> <ports...>`` from SPICE files, honouring '+' continuations.

    Returns name -> (port list, file it came from). The port order matters: the PDK cell
    subckts put the output first (``.subckt sg13g2_nand2_1 Y A B VDD VSS``), which is not
    the Verilog port order, so instances must be emitted positionally from this.
    """
    found: dict[str, tuple[list[str], Path]] = {}
    for path in paths:
        pending: str | None = None
        ports: list[str] = []
        for raw in path.read_text().splitlines():
            line = raw.split("$")[0].rstrip()
            if line.lstrip().startswith("*"):
                continue
            if pending is not None and line.lstrip().startswith("+"):
                ports.extend(line.lstrip()[1:].split())
                continue
            if pending is not None:
                found.setdefault(pending, (ports, path))
                pending = None
            m = _RE_SUBCKT.match(line)
            if m:
                pending = m.group(1)
                ports = m.group(2).split()
        if pending is not None:
            found.setdefault(pending, (ports, path))
    return found


